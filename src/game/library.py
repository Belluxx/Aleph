def root(cache_dir=None):
    """Library root; passing cache_dir (Aleph's --cache-dir) makes it the root for later calls too."""
    global _root
    if cache_dir is not None:
        _root = Path(cache_dir).expanduser() / "library"
    return _root or DEFAULT_CACHE / "library"


