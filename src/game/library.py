# Assets


def asset(name):
    """The library model name, generated on first use."""
    from . import assets

    folder = root() / "assets" / name
    meta = _read(folder / "asset.json")
    if meta.get("version") != MODELS or not all((folder / f"lod{i}.glb").is_file() for i in range(3)):
        meta = _build(name, assets.MODELS[name](), folder)
    colliders = [Collider(c["shape"], vertices=None if c.get("vertices") is None else np.asarray(c["vertices"], np.float32),
                          params=c.get("params", {})) for c in meta["colliders"]]
    return Asset(name, [f"assets/{name}/lod{i}.glb" for i in range(3)], colliders, meta["height"], meta["radius"])


def _build(name, model, folder):
    """Write a generated model's LOD files (and a tree's imposter maps first, which its LOD2 uses)."""
    if model.impostor is not None:
        target = root() / "materials" / model.impostor[0]
        color, normal, orm = model.impostor[1]
        _save(target / "color.png", color)
        _save(target / "normal.png", normal)
        _save(target / "orm.png", orm)
        write_json(target / "meta.json", dict(color="color.png", source="Aleph procedural (rendered imposter)",
                                              license="CC0", key=_key(model.impostor[0])))
    used = set()
    for i, parts in enumerate(model.lods):
        used |= {part.material for part in parts}
        node = gltf.Node(name, parts, colliders=model.colliders if i == 0 else [])
        gltf.write(folder / f"lod{i}.glb", [node], material, root())
    colliders = [dict(shape=c.shape, params=c.params, vertices=None if c.vertices is None else np.round(c.vertices, 4).tolist())
                 for c in model.colliders]
    meta = dict(version=MODELS, height=round(model.height, 3), radius=round(model.radius, 3), materials=sorted(used),
                triangles=[sum(len(p.indices) // 3 for p in parts) for parts in model.lods], colliders=colliders)
    write_json(folder / "asset.json", meta)
    return meta


