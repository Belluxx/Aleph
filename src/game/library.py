# Materials


def material(name):
    """The library material name, made on first use."""
    spec = MATERIALS[name]
    if "alias" in spec:  # Same maps as another material; only the extras differ.
        base = material(spec["alias"])
        base.name = name
        base.extras = dict(base.extras, **spec.get("extras", {}))
        return base
    folder = root() / "materials" / name
    meta = _read(folder / "meta.json")
    if meta.get("key") != _key(name):
        meta = _make(name, spec, folder)
    base = MATERIALS[spec["like"]] if "like" in spec else spec
    maps = f"materials/{spec.get('like', name)}"
    extras = dict(license=meta["license"], source=meta["source"], **base.get("extras", {}))
    if "emissive" in spec:
        extras["emissive"] = list(spec["emissive"])
    if meta.get("height"):
        extras.update(height=f"{maps}/height.png", parallax=base["parallax"])
    return Material(name, base["size"], base_color=f"materials/{name}/{meta['color']}", normal=f"{maps}/normal.png",
                    orm=f"{maps}/orm.png", roughness=1.0, metallic=1.0, alpha=base.get("alpha", "OPAQUE"),
                    double_sided=base.get("double_sided", False), extras=extras)


def _key(name):
    spec = MATERIALS[name]
    parts = [spec, MATERIALS.get(spec.get("like"))]
    if not spec.get("acg") or "make" in spec:
        parts.append(PROCEDURAL)
    if spec.get("make") == "impostor":
        parts.append(MODELS)
    return hashlib.sha256(repr(parts).encode()).hexdigest()[:16]


def _read(path):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return {}


def _make(name, spec, folder):
    """Download or generate a material's maps, recording where they came from in meta.json."""
    if "like" in spec:
        material(spec["like"])
        base = root() / "materials" / spec["like"]
        color = Image.open(base / _read(base / "meta.json")["color"]).convert("RGB")
        _save_color(folder, _tint(color, spec["tint"]))
        meta = dict(_read(base / "meta.json"), color="color.jpg")
    elif spec.get("make") == "impostor":
        from . import assets

        tree = "tree/" + name.rsplit("-", 1)[1]
        _build(tree, assets.MODELS[tree](), root() / "assets" / tree)  # Renders the imposter maps into folder.
        meta = dict(_read(folder / "meta.json"), color="color.png")
    else:
        maps, source = None, "Aleph procedural (numpy)"
        if spec.get("acg"):
            try:
                maps = _fetch(spec["acg"], spec.get("res", 2048))
                source = f"ambientCG {spec['acg']}"
            except Exception:  # Offline, moved, or broken: the procedural stand-in keeps builds going.
                maps = None
        color, normal, orm, height = _texture(name, spec, maps)
        meta = dict(color=_save_color(folder, color), source=source, license="CC0")
        _save(folder / "normal.png", normal)
        _save(folder / "orm.png", orm)
        if spec.get("parallax") and height is not None:
            _save(folder / "height.png", _height(height))
            meta["height"] = True
        if spec.get("acg") and maps is None:
            meta["fallback"] = True
    meta["key"] = _key(name)
    write_json(folder / "meta.json", meta)
    return meta


def _fetch(asset_id, res):
    """ambientCG maps of one set as Pillow images, read from the zip in memory; the zip is deleted."""
    label = "2K" if res > 1024 else "1K"
    folder = root() / "downloads"
    folder.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=folder) as temporary:
        path = Client().get(DOWNLOAD.format(asset_id, label), destination=Path(temporary) / "set.zip", timeout=120)
        maps = {}
        with zipfile.ZipFile(path) as archive:
            for entry in archive.namelist():
                found = re.search(r"_(Color|NormalGL|AmbientOcclusion|Roughness|Metalness|Opacity|Displacement)\.(jpg|png)$",
                                  entry)
                if found:
                    image = Image.open(BytesIO(archive.read(entry)))
                    image.load()
                    maps[found[1]] = image
    if not {"Color", "NormalGL", "Roughness"} <= maps.keys():
        raise ValueError(f"ambientCG {asset_id} lacks colour, normal, or roughness maps.")
    return maps


def _texture(name, spec, maps):
    """(colour, normal, orm, height or None) arrays for a material from downloaded maps, a special maker, or its
    fallback recipe."""
    res = spec.get("res", 2048 if maps else 1024)
    make = spec.get("make")
    if make:
        if make not in MAKERS:
            from . import textures

            MAKERS.update(textures.MAKERS)
        made = MAKERS[make](spec, res, maps, _rng(name))
        return (*made, None) if len(made) == 3 else made
    if maps:
        color = np.asarray(_tint(maps["Color"].convert("RGB"), spec.get("tint")).resize((res, res), Image.LANCZOS))
        normal = np.asarray(maps["NormalGL"].convert("RGB").resize((res, res), Image.LANCZOS))
        side = min(res, 1024)  # Roughness and occlusion are low-frequency: 1K keeps the cache lean.
        gray = lambda key, fill: (np.asarray(maps[key].convert("L").resize((side, side), Image.LANCZOS), float) / 255
                                  if key in maps else np.full((side, side), fill))
        metal = gray("Metalness", 0.0) if spec.get("metal") is None else np.full((side, side), float(spec["metal"]))
        # Some sets ship roughness far too glossy for what they show (Grass004 reads white at grazing angles).
        rough = np.clip(np.maximum(gray("Roughness", 1.0) * spec.get("rough", 1.0), spec.get("rough_min", 0.0)), 0, 1)
        orm = pack_orm(gray("AmbientOcclusion", 1.0), rough, metal)
        return color, normal, orm, _displacement(maps)
    return _procedural(spec["fallback"], res, _rng(name))


def _displacement(maps):
    """ambientCG's displacement as a float array, or None."""
    if not maps or "Displacement" not in maps:
        return None
    image = maps["Displacement"]
    if image.mode in ("I", "I;16", "F"):
        return np.asarray(image, float)
    return np.asarray(image.convert("L"), float)


def _height(height):
    """A height field as the stored map: HEIGHT² 8-bit greyscale, white = high, stretched to the full range."""
    height = np.asarray(height, float)
    if height.shape != (HEIGHT, HEIGHT):
        height = np.asarray(Image.fromarray(height.astype(np.float32), "F").resize((HEIGHT, HEIGHT), Image.BILINEAR), float)
    lo, hi = np.percentile(height, [0.5, 99.5])
    return (np.clip((height - lo) / max(hi - lo, 1e-9), 0, 1) * 255 + 0.5).astype(np.uint8)


def pack_orm(occlusion, roughness, metallic):
    """glTF's packed map: occlusion in R, roughness in G, metallic in B, from 0–1 arrays."""
    return (np.clip(np.stack(np.broadcast_arrays(occlusion, roughness, metallic), -1), 0, 1) * 255 + 0.5).astype(np.uint8)


def _tint(image, color):
    """Scale channels so the image's mean colour becomes color (sRGB), keeping its texture."""
    if color is None:
        return image
    data = np.asarray(image, float)
    mean = data.reshape(-1, data.shape[-1])[:, :3].mean(0)
    data[..., :3] *= np.asarray(color, float) / np.maximum(mean, 1)
    return Image.fromarray(np.clip(data, 0, 255).astype(np.uint8))


def _save_color(folder, color):
    """Colour as JPG to keep the cache small, or PNG when it carries alpha."""
    if isinstance(color, Image.Image):
        color = np.asarray(color)
    if color.shape[-1] == 4:
        _save(folder / "color.png", color)
        return "color.png"
    folder.mkdir(parents=True, exist_ok=True)
    with atomic_path(folder / "color.jpg") as temporary:
        Image.fromarray(color).save(temporary, "JPEG", quality=90)
    return "color.jpg"


def _save(path, array):
    path.parent.mkdir(parents=True, exist_ok=True)
    with atomic_path(path) as temporary:
        Image.fromarray(np.ascontiguousarray(array, np.uint8)).save(temporary, "PNG")


def _rng(name):
    return np.random.default_rng(int.from_bytes(hashlib.sha256(name.encode()).digest()[:8], "little"))


# Procedural textures: tileable value noise and simple patterns, so every material works offline.


def _noise(rng, n, cells):
    """Tileable value noise in [0, 1] on an n × n image with a cells × cells lattice."""
    grid = rng.random((cells, cells))
    t = np.arange(n) * cells / n
    i = t.astype(int)
    f = t - i
    f = f * f * (3 - 2 * f)
    j = (i + 1) % cells
    fx, fy = f[None, :], f[:, None]
    return ((grid[np.ix_(i, i)] * (1 - fx) + grid[np.ix_(i, j)] * fx) * (1 - fy)
            + (grid[np.ix_(j, i)] * (1 - fx) + grid[np.ix_(j, j)] * fx) * fy)


def _fbm(rng, n, cells=4, octaves=6):
    """Fractal noise normalised to [0, 1]."""
    total = sum(0.55 ** k * _noise(rng, n, cells * 2 ** k) for k in range(octaves) if cells * 2 ** k <= n // 2)
    return (total - total.min()) / max(np.ptp(total), 1e-9)


def _normal(height, strength):
    """OpenGL normal map (+Y up the texture) from a tileable height field in pixels × strength."""
    du = (np.roll(height, -1, 1) - np.roll(height, 1, 1)) * strength / 2
    dv = (np.roll(height, 1, 0) - np.roll(height, -1, 0)) * strength / 2  # Rows run down, v runs up.
    n = np.stack((-du, -dv, np.ones_like(height)), -1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    return ((n + 1) * 127.5).astype(np.uint8)


def _blur(array, radius):
    """Tileable box blur, applied twice (close to a Gaussian)."""
    for _ in range(2):
        for axis in (0, 1):
            array = sum(np.roll(array, k, axis) for k in range(-radius, radius + 1)) / (2 * radius + 1)
    return array


def _blocks(rng, n, rows, cols, mortar, offset=0.5, jitter=0.0, round_=False):
    """Height (0 in joints, up to 1 on faces) and a per-block random value for bricks, tiles, and cobbles."""
    y, x = np.mgrid[0:n, 0:n] / n
    row = np.floor(y * rows).astype(int)
    shift = (row * offset + rng.random(rows)[row] * jitter) % 1
    u = (x * cols + shift) % cols
    col = np.floor(u).astype(int) % cols
    fx, fy = u % 1, (y * rows) % 1
    w, h = n / cols, n / rows  # Block size in pixels.
    edge = np.minimum(np.minimum(fx, 1 - fx) * w, np.minimum(fy, 1 - fy) * h)
    gap = mortar * n
    height = np.clip((edge - gap) / max(gap * 1.5, 1.5), 0, 1)
    if round_:
        height *= np.clip(np.sqrt(np.clip(1 - ((fx - 0.5) * 2) ** 2, 0, 1) * np.clip(1 - ((fy - 0.5) * 2) ** 2, 0, 1)) * 1.5, 0, 1)
    return height, rng.random(rows * cols)[row * cols + col]


def _procedural(recipe, n, rng):
    """(colour, normal, orm) from a fallback recipe: colour, noise variation, grain, and an optional pattern."""
    base = np.asarray(recipe["color"], float)
    noise, grain = _fbm(rng, n, 4), _fbm(rng, n, 64, 3)
    shade = 1 + recipe.get("vary", 0.1) * (noise - 0.5) * 2 + recipe.get("grain", 0.15) * (grain - 0.5)
    height = noise * 2 + grain * 2
    pattern = recipe.get("pattern")
    if pattern in ("bricks", "tiles", "cobbles"):
        rows, cols = recipe["rows"], recipe["cols"]
        mortar = {"tiles": 0.004, "bricks": 0.005}.get(pattern, 0.012)
        faces, each = _blocks(rng, n, rows, cols, mortar, 0.5 if pattern == "bricks" else 0.0,
                              0.6 if pattern == "cobbles" else 0.0, pattern == "cobbles")
        shade = shade * (1 + 0.18 * (each - 0.5))
        joint = np.asarray(recipe.get("mortar", base * 0.6), float)
        color = base * shade[..., None] * faces[..., None] + joint * (1 - faces[..., None]) * (0.9 + 0.2 * grain[..., None])
        height = faces * 6 + grain * 1.5
        occlusion = 0.7 + 0.3 * _blur(faces, 2)
    elif pattern in ("bark", "planks"):
        stretch = np.repeat(_fbm(rng, n, 8, 4).mean(0, keepdims=True), n, 0) if pattern == "planks" else None
        ridges = np.abs(np.sin((np.arange(n)[None, :] / n * 24 + noise * 6) * np.pi)) ** 0.5
        if pattern == "bark":
            ridges = ridges * (0.6 + 0.4 * _fbm(rng, n, 16, 3))
            color = base * (0.55 + 0.6 * ridges[..., None]) * shade[..., None]
            height = ridges * 8
        else:
            color = base * (0.85 + 0.25 * stretch[..., None] + 0.1 * (ridges[..., None] - 0.5)) * shade[..., None]
            height = ridges
        occlusion = 0.75 + 0.25 * height / max(height.max(), 1e-9)
    else:
        color = base * shade[..., None]
        occlusion = 0.85 + 0.15 * noise
    rough = np.clip(recipe.get("rough", 0.8) * (0.9 + 0.2 * grain), 0, 1)
    orm = pack_orm(occlusion, rough, recipe.get("metal", 0.0))
    return np.clip(color, 0, 255).astype(np.uint8), _normal(height, recipe.get("bump", 1.0)), orm, height


def _make_marking(spec, n, maps, rng):
    """Road paint: opaque with worn holes (alpha), rough and slightly grainy."""
    wear = _fbm(rng, n, 8) * 0.7 + _fbm(rng, n, 64, 2) * 0.3
    alpha = np.where(wear > 0.22, 255, 0).astype(np.uint8)
    color = np.asarray(spec["fallback"]["color"], float) * (0.92 + 0.12 * wear[..., None])
    rgba = np.dstack((np.clip(color, 0, 255).astype(np.uint8), alpha))
    return rgba, _normal(wear * 2, 1.0), pack_orm(1.0, 0.65 + 0.2 * wear, 0.0)


def _make_water(spec, n, maps, rng):
    """Calm water: dark tint, glossy, small tileable ripples."""
    y, x = np.mgrid[0:n, 0:n] / n * 2 * np.pi
    waves = sum(np.sin(a * x + b * y + rng.random() * 6.3) / (abs(a) + abs(b))
                for a, b in [(3, 1), (-2, 4), (5, -3), (1, -6), (7, 2), (-4, -5)])
    height = waves * 1.5 + _fbm(rng, n, 16, 3) * 2
    color = np.asarray(spec["fallback"]["color"], float) * (0.9 + 0.2 * _fbm(rng, n, 2, 3))[..., None]
    return color.astype(np.uint8), _normal(height, 0.6), pack_orm(1.0, np.full((n, n), 0.04), 0.0)


def _make_glass(spec, n, maps, rng):
    """Dark, glossy glass with faint smudges, so reflections carry the look."""
    smudge = _fbm(rng, n, 4, 4)
    color = np.asarray(spec["fallback"]["color"], float) * (0.95 + 0.1 * smudge[..., None])
    return color.astype(np.uint8), _normal(smudge, 0.2), pack_orm(1.0, 0.03 + 0.08 * smudge, 0.0)


def _make_curtain(spec, n, maps, rng):
    """Curtain wall: two 1.5 m glass panes per repeat with metal mullions and a spandrel band at the slab."""
    px = n / 3.0  # Pixels per metre.
    y, x = np.mgrid[0:n, 0:n]
    mullion = (np.abs((x % (1.5 * px)) - 0.75 * px) > 0.75 * px - 0.04 * px)
    band = (y % n) > n - 0.45 * px  # Spandrel above the slab, at the bottom of each floor.
    frame = mullion | band | (np.abs(y - (n - 0.45 * px)) < 0.03 * px)
    pane = (x // (1.5 * px)).astype(int)
    glass = np.asarray(spec["fallback"]["color"], float) * (0.85 + 0.3 * rng.random(2)[pane % 2])[..., None]
    glass = glass * (0.9 + 0.2 * (y / n))[..., None]  # Sky reflection is brighter towards the top.
    color = np.where(frame[..., None], np.array([120, 124, 128.0]), glass)
    color = np.where(band[..., None] & ~mullion[..., None], np.array([52, 60, 66.0]), color)
    height = frame * 6.0
    orm = pack_orm(np.where(frame, 1.0, 0.95), np.where(frame, 0.4, 0.04), np.where(frame, 1.0, 0.0))
    return color.astype(np.uint8), _normal(_blur(height, 1), 1.0), orm


def _make_paint(spec, n, maps, rng):
    """Near-white painted metal for vertex-coloured props, with slight wear."""
    wear = _fbm(rng, n, 8, 5)
    color = np.asarray(spec["fallback"]["color"], float) * (0.94 + 0.08 * wear[..., None])
    return color.astype(np.uint8), _normal(wear, 0.5), pack_orm(1.0, 0.4 + 0.15 * wear, 0.0)


def _make_flat(spec, n, maps, rng):
    recipe = spec["fallback"]
    color = np.broadcast_to(np.asarray(recipe["color"], np.uint8), (n, n, 3))
    return color, np.broadcast_to(np.array([128, 128, 255], np.uint8), (n, n, 3)), pack_orm(1.0, np.full((n, n), recipe["rough"]), 0.0)


def _make_birch(spec, n, maps, rng):
    """Birch bark: chalky white with dark horizontal lenticels and blotches."""
    y, x = np.mgrid[0:n, 0:n] / n
    lenticels = (_noise(rng, n, 48) > 0.78) & (np.abs(np.sin(y * 70 * np.pi)) < 0.25)
    blotch = _fbm(rng, n, 4) > 0.72
    dark = np.clip(lenticels * 0.9 + blotch * 0.75, 0, 1)
    color = np.asarray(spec["fallback"]["color"], float) * (0.92 + 0.12 * _fbm(rng, n, 16, 3)[..., None])
    color = color * (1 - dark[..., None]) + np.array([38, 34, 32.0]) * dark[..., None]
    return color.astype(np.uint8), _normal(_blur(dark.astype(float), 1) * -4, 1.0), pack_orm(1 - 0.3 * dark, 0.7 + 0.2 * dark, 0.0)


def _make_foliage(spec, n, maps, rng):
    """Opaque leafy mass for hedge cores and distant bushes."""
    leaves = _fbm(rng, n, 32, 3)
    color = np.asarray(spec["fallback"]["color"], float) * (0.6 + 0.8 * leaves[..., None])
    return color.astype(np.uint8), _normal(leaves * 6, 1.0), pack_orm(0.6 + 0.4 * leaves, 0.8, 0.0)


def _make_door(spec, n, maps, rng):
    """A whole door leaf (unit UVs, 1:2): wood with six raised panels, or an aluminium frame around glass."""
    w, h = n // 2, n
    y, x = np.mgrid[0:h, 0:w]
    if spec.get("acg"):
        if maps:
            wood = np.asarray(_tint(maps["Color"].convert("RGB"), spec["fallback"]["color"]).rotate(90).resize((w, h)), float)
        else:
            wood = _procedural(dict(spec["fallback"], pattern="planks"), h, rng)[0]
            wood = wood[:, :w].astype(float)
        # Panels: 2 columns × 3 rows inside a 9 % stile frame; panel edges are bevelled.
        inner = np.zeros((h, w))
        for c in range(2):
            for r, (top, bottom) in enumerate([(0.06, 0.36), (0.40, 0.70), (0.74, 0.94)]):
                x0, x1 = (0.11 + c * 0.42) * w, (0.47 + c * 0.42) * w
                y0, y1 = top * h, bottom * h
                edge = np.minimum(np.minimum(x - x0, x1 - x), np.minimum(y - y0, y1 - y))
                inner = np.maximum(inner, np.clip(edge / (0.025 * w), 0, 1) * (edge > 0))
        height = 4 - inner * 2 + (inner >= 1) * 3
        knob = (x - 0.86 * w) ** 2 + (y - 0.55 * h) ** 2 < (0.03 * w) ** 2
        color = wood * (0.9 + 0.1 * inner[..., None]) * np.where((inner > 0) & (inner < 1), 0.7, 1.0)[..., None]
        color[knob] = [190, 150, 80]
        orm = pack_orm(0.75 + 0.25 * np.clip(inner + (inner == 0), 0, 1), np.where(knob, 0.3, 0.55), np.where(knob, 1.0, 0.0))
    else:
        frame = (x < 0.09 * w) | (x > 0.91 * w) | (y < 0.05 * h) | (y > 0.88 * h)
        bar = (np.abs(y - 0.52 * h) < 0.012 * h) & (x > 0.15 * w) & (x < 0.85 * w)
        glass = np.array([30, 38, 44.0]) * (0.9 + 0.2 * y / h)[..., None]
        color = np.where((frame | bar)[..., None], np.asarray(spec["fallback"]["color"], float), glass)
        height = frame * 4.0 + bar * 6.0
        orm = pack_orm(1.0, np.where(frame | bar, 0.35, 0.04), np.where(frame | bar, 1.0, 0.0))
    return np.clip(color, 0, 255).astype(np.uint8), _normal(_blur(height, 1), 1.0), orm


def _leaf_stamp(maps, rng):
    """One RGBA leaf pointing up, from ambientCG's leaf photo or drawn procedurally."""
    if maps and "Opacity" in maps:
        color = maps["Color"].convert("RGB")
        alpha = maps["Opacity"].convert("L")
        leaf = Image.merge("RGBA", (*color.split(), alpha))
        box = leaf.getchannel("A").crop((0, 0, leaf.width // 2, leaf.height)).getbbox()
        return leaf.crop(box) if box else leaf
    leaf = Image.new("RGBA", (200, 320), (0, 0, 0, 0))
    draw = ImageDraw.Draw(leaf)
    outline = [(100 + 95 * np.sin(t) * (1 - t / np.pi) ** 0.3 * np.sin(t) ** 0.4, 300 - t / np.pi * 290)
               for t in np.linspace(0, np.pi, 40)]
    outline += [(200 - px, py) for px, py in reversed(outline)]
    draw.polygon(outline, fill=(84, 120, 48, 255))
    draw.line([(100, 320), (100, 20)], fill=(120, 150, 70, 255), width=5)
    return leaf


def _make_leaves(spec, n, maps, rng, conifer=False):
    """2 × 2 atlas of leafy twigs: RGBA colour with alpha cut-outs, tilted per-leaf normals, darker centres.

    Each cluster is drawn in its own cell image, so leaves never spill into a neighbouring cell's cards.
    """
    half = n // 2
    color = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    normal = Image.new("RGB", (n, n), (128, 128, 255))
    occlusion = Image.new("L", (n, n), 255)
    stamp = None if conifer else _leaf_stamp(maps, rng)
    tint = np.asarray(spec["fallback"]["color"], float)
    for cell in range(4):
        cc, cn, co = Image.new("RGBA", (half, half), (0, 0, 0, 0)), Image.new("RGB", (half, half), (128, 128, 255)), \
            Image.new("L", (half, half), 255)
        draw, ndraw, odraw = ImageDraw.Draw(cc), ImageDraw.Draw(cn), ImageDraw.Draw(co)
        # A main twig from the bottom centre with side twigs, then leaves or needles along them.
        base = np.array([half * 0.5, half * 0.98])
        angle = -np.pi / 2 + rng.normal(0, 0.12)
        main = [base + np.array([np.cos(angle), np.sin(angle)]) * half * t for t in np.linspace(0, 0.72, 8)]
        twigs = [main]
        for k in range(5 if conifer else 6):
            side = angle + (1 if k % 2 else -1) * rng.uniform(0.5, 0.9)
            twigs.append([main[2 + k % 5] + np.array([np.cos(side), np.sin(side)]) * half * t
                          for t in np.linspace(0, 0.3 if conifer else 0.26, 5)])
        for twig in twigs:
            draw.line([tuple(p) for p in twig], fill=(70, 55, 40, 255), width=max(2, n // 400))
        for twig in twigs:
            for p0, p1 in zip(twig, twig[1:]):
                direction = np.arctan2(*(p1 - p0)[::-1])
                for _ in range(24 if conifer else 3):
                    p = p0 + (p1 - p0) * rng.random()
                    shade = rng.uniform(0.75, 1.2)
                    tilt = rng.normal(0, 0.35, 2)
                    nrm = np.array([tilt[0], tilt[1], 1.0]) / np.linalg.norm([tilt[0], tilt[1], 1.0])
                    ncol = tuple(int(v) for v in (nrm + 1) * 127.5)
                    depth = int(255 * np.clip(0.55 + 0.6 * np.linalg.norm(p - half / 2) / half, 0, 1))
                    if conifer:  # Paired needles angled forward along the twig, denser towards its tip.
                        for sign in (-1, 1):
                            a = direction + sign * rng.uniform(0.35, 0.85)
                            q = p + np.array([np.cos(a), np.sin(a)]) * half * rng.uniform(0.07, 0.13)
                            c = tuple(int(v) for v in np.clip(tint * shade, 0, 255)) + (255,)
                            for target, value in ((draw, c), (ndraw, ncol), (odraw, depth)):
                                target.line([tuple(p), tuple(q)], fill=value, width=max(2, n // 300))
                        continue
                    size = half * rng.uniform(0.16, 0.24)
                    leaf = stamp.resize((max(1, int(size * stamp.width / stamp.height)), int(size)), Image.LANCZOS)
                    a = np.degrees(-direction) - 90 + rng.normal(0, 20) + rng.choice([-1, 1]) * rng.uniform(25, 60)
                    leaf = leaf.rotate(a, expand=True, resample=Image.BICUBIC)
                    rgb = np.asarray(leaf, float)
                    opaque = rgb[..., 3] > 128
                    mean = rgb[..., :3][opaque].mean(0) if opaque.any() else tint
                    rgb[..., :3] *= tint * shade / np.maximum(mean, 1)
                    leaf = Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8))
                    at = (int(p[0] - leaf.width / 2), int(p[1] - leaf.height / 2))
                    region = (*at, at[0] + leaf.width, at[1] + leaf.height)
                    cc.alpha_composite(leaf, (max(at[0], 0), max(at[1], 0)), (max(-at[0], 0), max(-at[1], 0)))
                    cn.paste(ncol, region, leaf.getchannel("A"))
                    co.paste(depth, region, leaf.getchannel("A"))
        if conifer:  # Needle tufts bursting from each twig tip.
            for twig in twigs:
                tip, back = twig[-1], twig[-2]
                direction = np.arctan2(*(tip - back)[::-1])
                for _ in range(16):
                    a = direction + rng.normal(0, 0.6)
                    q = tip + np.array([np.cos(a), np.sin(a)]) * half * rng.uniform(0.06, 0.12)
                    c = tuple(int(v) for v in np.clip(tint * rng.uniform(0.8, 1.25), 0, 255)) + (255,)
                    draw.line([tuple(tip), tuple(q)], fill=c, width=max(2, n // 300))
                    ndraw.line([tuple(tip), tuple(q)], fill=(128, 150, 240), width=max(2, n // 300))
                    odraw.line([tuple(tip), tuple(q)], fill=255, width=max(2, n // 300))
        corner = (cell % 2 * half, cell // 2 * half)
        color.paste(cc, corner)
        normal.paste(cn, corner)
        occlusion.paste(co, corner)
    rgba = np.asarray(color).copy()
    # Bleed colour into transparent texels so mipmaps don't fringe dark.
    solid = rgba[..., 3] > 128
    rgba[~solid, :3] = (rgba[solid, :3].mean(0) if solid.any() else tint).astype(np.uint8)
    rgba[..., 3] = np.where(solid, 255, 0)
    orm = pack_orm(np.asarray(occlusion, float) / 255, 0.6, 0.0)
    return rgba, np.asarray(normal), orm


def _make_signs(spec, n, maps, rng):
    """2 × 2 atlas of German sign faces: prohibition (250), no stopping (283), stop (206), give way (205)."""
    image = Image.new("RGB", (n, n), (200, 200, 200))
    draw = ImageDraw.Draw(image)
    half, red, blue, white = n // 2, (200, 30, 35), (20, 70, 160), (245, 245, 245)
    for cell in range(4):
        ox, oy = cell % 2 * half, cell // 2 * half
        c, r = (ox + half / 2, oy + half / 2), half * 0.48
        box = lambda s: (c[0] - r * s, c[1] - r * s, c[0] + r * s, c[1] + r * s)
        if cell == 0:
            draw.ellipse(box(1), fill=red)
            draw.ellipse(box(0.78), fill=white)
        elif cell == 1:
            draw.ellipse(box(1), fill=red)
            draw.ellipse(box(0.78), fill=blue)
            for s in (1, -1):
                draw.line([(c[0] - r * 0.55, c[1] - s * r * 0.55), (c[0] + r * 0.55, c[1] + s * r * 0.55)], fill=red,
                          width=int(r * 0.2))
        elif cell == 2:
            octagon = lambda s: [(c[0] + r * s * np.cos(a), c[1] + r * s * np.sin(a)) for a in np.arange(8) * np.pi / 4 + np.pi / 8]
            draw.polygon(octagon(1), fill=white)
            draw.polygon(octagon(0.92), fill=red)
            font = ImageFont.load_default(size=int(r * 0.6))
            draw.text(c, "STOP", fill=white, font=font, anchor="mm")
        else:
            triangle = lambda s: [(c[0] + r * s * np.cos(a), c[1] + r * s * np.sin(a)) for a in np.radians([90, 210, 330])]
            draw.polygon(triangle(1), fill=red)
            draw.polygon(triangle(0.68), fill=white)
    color = np.asarray(image)
    return color, np.broadcast_to(np.array([128, 128, 255], np.uint8), color.shape).copy(), pack_orm(1.0, np.full((n, n), 0.4), 0.0)


