# Packaging


def install(names, dest):
    """Copy the given materials and assets (with the materials they use) into dest, mirroring the cache layout."""
    dest, files = Path(dest), set()
    pending = list(names)
    while pending:
        name = pending.pop()
        if name in MATERIALS:
            m = material(name)
            files |= {m.base_color, m.normal, m.orm} | ({m.extras["height"]} if "height" in m.extras else set())
        else:
            a = asset(name)
            files |= set(a.lods)
            pending += _read(root() / "assets" / name / "asset.json")["materials"]
    for relative in sorted(files):
        source, target = root() / relative, dest / relative
        if not target.is_file() or target.stat().st_size != source.stat().st_size or target.stat().st_mtime < source.stat().st_mtime:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
    return sorted(files)


def prepare(names=None, progress=None):
    """Make the given (default: all) materials and assets now, retrying materials that fell back to procedural."""
    names = list(names) if names is not None else catalog()
    for done, name in enumerate(names):
        if progress:
            progress("Preparing asset library", done, len(names), "items")
        if name in MATERIALS:
            folder = root() / "materials" / name
            if _read(folder / "meta.json").get("fallback"):
                _make(name, MATERIALS[name], folder)
            material(name)
        else:
            asset(name)
    if progress:
        progress("Preparing asset library", len(names), len(names), "items")
